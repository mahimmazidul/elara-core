#!/usr/bin/env python3
"""Aggregate local participant-level predictions; never export raw records."""
import argparse
import collections
import json
import math
import random
import statistics
from pathlib import Path

METHODS = ("elara", "openciclo", "flowlytics", "fixed28", "last_cycle", "personal_median")


def q(values, fraction):
    ordered = sorted(values)
    if not ordered:
        return None
    position = (len(ordered) - 1) * fraction
    low = math.floor(position)
    high = math.ceil(position)
    return ordered[low] + (ordered[high] - ordered[low]) * (position - low)


def metrics(rows, method):
    selected = [r for r in rows if method in r]
    if not selected:
        return None
    errors = [r[method]["error_days"] for r in selected]
    absolute = [abs(e) for e in errors]
    by_person = collections.defaultdict(list)
    for row, ae in zip(selected, absolute):
        by_person[row["person"]].append(ae)
    m = {
        "forecasts": len(selected),
        "participants": len(by_person),
        "mae_days": statistics.mean(absolute),
        "person_weighted_mae_days": statistics.mean(statistics.mean(v) for v in by_person.values()),
        "median_abs_error_days": statistics.median(absolute),
        "p90_abs_error_days": q(absolute, 0.9),
        "max_abs_error_days": max(absolute),
        "mean_signed_error_days_late_positive": statistics.mean(errors),
        "exact_rate": sum(a == 0 for a in absolute) / len(absolute),
        "within_1_day_rate": sum(a <= 1 for a in absolute) / len(absolute),
        "within_2_days_rate": sum(a <= 2 for a in absolute) / len(absolute),
        "within_3_days_rate": sum(a <= 3 for a in absolute) / len(absolute),
        "within_5_days_rate": sum(a <= 5 for a in absolute) / len(absolute),
        "over_7_days_rate": sum(a > 7 for a in absolute) / len(absolute),
    }
    if "window_days" in selected[0][method]:
        radii = [r[method]["window_days"] for r in selected]
        m.update({
            "window_coverage": sum(a <= w for a, w in zip(absolute, radii)) / len(absolute),
            "mean_window_radius_days": statistics.mean(radii),
            "median_window_radius_days": statistics.median(radii),
            "window_radius_distribution": dict(sorted(collections.Counter(radii).items())),
            "mean_score": statistics.mean(r[method]["score"] for r in selected),
        })
    return m


def participant_bootstrap(rows, method="elara", comparison=None, seed=20261108, replicates=3000):
    """Pooled forecasts, resampling whole participants (percentile interval)."""
    people = collections.defaultdict(list)
    for r in rows:
        if method in r and (comparison is None or comparison in r):
            people[r["person"]].append(r)
    summaries = []
    for records in people.values():
        n = len(records)
        loss = sum(abs(r[method]["error_days"]) for r in records)
        covered = sum(abs(r[method]["error_days"]) <= r[method]["window_days"] for r in records)
        other = (sum(abs(r[comparison]["error_days"]) for r in records)
                 if comparison is not None else 0)
        summaries.append((n, loss, covered, other))
    rng = random.Random(seed)
    maes, covers, differences = [], [], []
    for _ in range(replicates):
        sample = rng.choices(summaries, k=len(summaries))
        n = sum(s[0] for s in sample)
        loss = sum(s[1] for s in sample)
        maes.append(loss / n)
        covers.append(sum(s[2] for s in sample) / n)
        if comparison is not None:
            differences.append((loss - sum(s[3] for s in sample)) / n)
    result = {
        "resampling_unit": "participant",
        "replicates": replicates,
        "seed": seed,
        "elara_mae_95_percentile_interval_days": [q(maes, .025), q(maes, .975)],
        "elara_window_coverage_95_percentile_interval": [q(covers, .025), q(covers, .975)],
    }
    if comparison is not None:
        result[f"elara_minus_{comparison}_mae_95_percentile_interval_days"] = [
            q(differences, .025), q(differences, .975)
        ]
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("predictions", help="local JSONL generated by walk_forward.dart")
    args = parser.parse_args()
    rows = [json.loads(line) for line in Path(args.predictions).read_text().splitlines() if line.strip()]
    if not rows:
        raise ValueError("No predictions")
    groups = {
        "all": rows,
        "zero_prior_completed_cycles": [r for r in rows if r["prior_completed_cycles"] == 0],
        "at_least_one_prior_completed_cycle": [r for r in rows if r["prior_completed_cycles"] >= 1],
        "at_least_three_prior_completed_cycles": [r for r in rows if r["prior_completed_cycles"] >= 3],
        "history_range_at_most_7_days_minimum_3_prior": [r for r in rows if r["prior_completed_cycles"] >= 3 and r["prior_range_days"] <= 7],
        "history_range_over_7_days_minimum_3_prior": [r for r in rows if r["prior_completed_cycles"] >= 3 and r["prior_range_days"] > 7],
        # Sensitivity only: labels outside the Flowlytics history filter are excluded.
        "target_length_15_to_50_days_sensitivity": [r for r in rows if 15 <= r["actual_length"] <= 50],
    }
    result = {name: {"sample": {"forecasts": len(group), "participants": len({r["person"] for r in group})},
                     "methods": {method: metrics(group, method) for method in METHODS}}
              for name, group in groups.items()}
    result["all"]["bootstrap_versus_fixed28"] = participant_bootstrap(groups["all"], comparison="fixed28")
    result["at_least_one_prior_completed_cycle"]["bootstrap_versus_last_cycle"] = participant_bootstrap(
        groups["at_least_one_prior_completed_cycle"], comparison="last_cycle")
    print(json.dumps(result, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
